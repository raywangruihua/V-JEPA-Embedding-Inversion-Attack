def load_dictionary(
    path: str,
    src: WordVectors,
    trg: WordVectors,
    encoding: str = "utf-8",
) -> Tuple[Dict[int, Set[int]], float]:
    """Read a gold dictionary and convert it to row indices.

    Expects one ``"<source> <target>"`` pair per line (the MUSE and VecMap
    format). Lines with more than two fields keep only the first two.

    Returns ``(gold, coverage)`` where ``gold`` maps a source index to the set
    of acceptable target indices, and ``coverage`` is the fraction of distinct
    source words whose pair survived the vocabulary lookup. Low coverage means
    the loaded vocabularies are too small for the test set to be meaningful.
    """
    gold: Dict[int, Set[int]] = collections.defaultdict(set)
    found: Set[str] = set()
    missing: Set[str] = set()

    with open(path, encoding=encoding, errors="surrogateescape") as handle:
        for line in handle:
            fields = line.split()
            if len(fields) < 2:
                continue
            src_word, trg_word = fields[0], fields[1]
            src_idx, trg_idx = src.index(src_word), trg.index(trg_word)
            if src_idx is None or trg_idx is None:
                missing.add(src_word)
            else:
                gold[src_idx].add(trg_idx)
                found.add(src_word)

    # A word is only missing if *none* of its translations were resolvable.
    missing -= found
    total = len(found) + len(missing)
    coverage = len(found) / total if total else 0.0
    return dict(gold), coverage


# =============================================================================
# 7. High-level entry point
# =============================================================================


def align(
    src: WordVectors,
    trg: WordVectors,
    src_lang: str = "src",
    trg_lang: str = "trg",
    **kwargs,
) -> Alignment:
    """Align two embedding spaces. One-call wrapper over
    :class:`GromovWassersteinAligner`.

    Any keyword accepted by :class:`GromovWassersteinAligner` may be passed
    through -- ``anchor_vocab``, ``entreg``, ``maxiter``, ``normalize_vecs`` and
    so on.

    Example
    -------
    ::

        src = WordVectors.load("wiki.en.vec", max_vocab=200_000)
        trg = WordVectors.load("wiki.es.vec", max_vocab=200_000)
        alignment = align(src, trg, "en", "es", anchor_vocab=2000)
    """
    return GromovWassersteinAligner(**kwargs).fit(src, trg, src_lang, trg_lang)


