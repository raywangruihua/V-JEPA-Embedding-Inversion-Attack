def _build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Unsupervised bilingual lexicon induction with Gromov-Wasserstein.",
        formatter_class=argparse.ArgumentDefaultsHelpFormatter,
    )

    data = parser.add_argument_group("data")
    data.add_argument("--src-vectors", required=True, help="source embedding file")
    data.add_argument("--trg-vectors", required=True, help="target embedding file")
    data.add_argument("--src-lang", default="src", help="source language code")
    data.add_argument("--trg-lang", default="trg", help="target language code")
    data.add_argument("--dictionary", help="gold dictionary for evaluation (optional)")
    data.add_argument("--max-vocab", type=int, default=200_000,
                      help="vectors to load per language")
    data.add_argument("--encoding", default="utf-8")
    data.add_argument("--outdir", help="directory for projected vectors and arrays")

    gw = parser.add_argument_group("Gromov-Wasserstein")
    gw.add_argument("--anchor-vocab", type=int, default=2000,
                    help="words per language in the GW problem (cost is quadratic)")
    gw.add_argument("--metric", default="cosine",
                    choices=["cosine", "euclidean", "sqeuclidean"])
    gw.add_argument("--normalize-vecs", default="both",
                    choices=["both", "mean", "unit", "whiten", "whiten_zca", "none"])
    gw.add_argument("--normalize-dists", default="mean",
                    choices=["mean", "max", "median", "none"])
    gw.add_argument("--loss", default=SQUARE_LOSS, choices=[SQUARE_LOSS, KL_LOSS])
    gw.add_argument("--entreg", type=float, default=5e-4,
                    help="entropic regularization")
    gw.add_argument("--tol", type=float, default=1e-9, help="outer stopping tolerance")
    gw.add_argument("--maxiter", type=int, default=300, help="outer iterations")
    gw.add_argument("--distribs", default="uniform", choices=["uniform", "zipf"])
    gw.add_argument("--anchor-method", default="mutual_nn", choices=["mutual_nn", "all"])
    gw.add_argument("--max-anchors", type=int, default=None)

    ev = parser.add_argument_group("retrieval and evaluation")
    ev.add_argument("--score-type", default="projected",
                    choices=["projected", "coupling", "barycentric"])
    ev.add_argument("--adjust", default="csls", choices=["csls", "none"])
    ev.add_argument("--retrieval-vocab", type=int, default=50_000,
                    help="candidate pool size for full-vocabulary retrieval")
    ev.add_argument("--log-every", type=int, default=10)
    ev.add_argument("--quiet", action="store_true")
    return parser


def main(argv: Optional[Sequence[str]] = None) -> int:
    """Run the full pipeline from the command line.

    ::

        python otalign.py --src-vectors wiki.en.vec --trg-vectors wiki.es.vec \\
            --src-lang en --trg-lang es --dictionary en-es.0-5000.txt \\
            --anchor-vocab 2000 --maxiter 300
    """
    args = _build_parser().parse_args(argv)
    verbose = not args.quiet

    if verbose:
        print(f"Loading {args.src_vectors} and {args.trg_vectors} "
              f"(up to {args.max_vocab} words each)...")
    src = WordVectors.load(args.src_vectors, args.max_vocab, args.encoding)
    trg = WordVectors.load(args.trg_vectors, args.max_vocab, args.encoding)
    if verbose:
        print(f"  source: {src}\n  target: {trg}")

    alignment = align(
        src,
        trg,
        args.src_lang,
        args.trg_lang,
        anchor_vocab=args.anchor_vocab,
        metric=args.metric,
        normalize_vecs=args.normalize_vecs,
        normalize_dists=args.normalize_dists,
        loss=args.loss,
        entreg=args.entreg,
        tol=args.tol,
        maxiter=args.maxiter,
        distribs=args.distribs,
        anchor_method=args.anchor_method,
        max_anchors=args.max_anchors,
        verbose=verbose,
        log_every=args.log_every,
    )
    alignment.score_type = args.score_type
    alignment.adjust = None if args.adjust == "none" else args.adjust

    if args.dictionary:
        gold, coverage = load_dictionary(args.dictionary, alignment.src, alignment.trg)
        print(f"\nGold dictionary: {len(gold)} source words, "
              f"{coverage:.2%} vocabulary coverage.")
        # Report every scoring route, as the original script did, so the effect
        # of the coupling / mapping / CSLS choices is visible side by side.
        for score_type in ("coupling", "barycentric", "projected"):
            for adjust in (None, "csls"):
                label = score_type + ("+csls" if adjust else "")
                n_trg = (
                    args.retrieval_vocab if score_type == "projected"
                    else alignment.n_anchor_trg
                )
                try:
                    precisions = alignment.precision_at_k(
                        gold, score_type=score_type, adjust=adjust, n_trg=n_trg
                    )
                except ValueError as exc:
                    print(f"  {label:22s} skipped ({exc})")
                    continue
                print("  {:22s} ".format(label)
                      + "  ".join("P@{}: {:6.2%}".format(k, v)
                                  for k, v in precisions.items()))

    if args.outdir:
        if verbose:
            print(f"\nWriting projected vectors and arrays to {args.outdir}...")
        alignment.export(args.outdir)

    return 0


if __name__ == "__main__":
    sys.exit(main())
