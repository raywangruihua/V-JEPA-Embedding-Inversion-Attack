@dataclass
class SinkhornState:
    """Scaling vectors carried between successive Sinkhorn solves (warm start).

    ``u`` and ``v`` are the multiplicative scalings such that the transport plan
    is ``diag(u) K diag(v)``. ``shift`` records the constant that was subtracted
    from the cost matrix when ``K`` was built, which is needed to reinterpret
    ``u``/``v`` against a differently shifted cost -- see :func:`sinkhorn`.
    """

    u: np.ndarray
    v: np.ndarray
    shift: float


def sinkhorn(
    a: np.ndarray,
    b: np.ndarray,
    M: np.ndarray,
    reg: float,
    warm_start: Optional[SinkhornState] = None,
    numItermax: int = 1000,
    stopThr: float = 1e-9,
    check_every: int = 10,
) -> Tuple[np.ndarray, SinkhornState, int, bool]:
    r"""Solve the entropy-regularized optimal transport problem.

    .. math::
        \min_T \langle T, M \rangle + \mathrm{reg} \sum_{ij} T_{ij}\log T_{ij}
        \quad\text{s.t.}\quad T\mathbf{1}=a,\; T^\top\mathbf{1}=b,\; T\ge 0

    via Sinkhorn-Knopp matrix scaling (Cuturi, 2013).

    Parameters
    ----------
    a, b:
        Source and target marginals, each summing to 1.
    M:
        Cost matrix of shape ``(len(a), len(b))``.
    reg:
        Entropic regularization strength. Smaller values give sharper, more
        permutation-like plans but are numerically harder.
    stopThr:
        Stopping threshold on the *squared* L2 error of the target marginal,
        ``||T^T 1 - b||^2``. Squared, and checked every ``check_every``
        iterations, to match the original implementation and POT so that
        published tolerances carry over unchanged. Note the asymmetry: the loop
        ends on the ``u`` update, so ``T 1 == a`` holds to machine precision
        while ``T^T 1 == b`` holds only to roughly ``sqrt(stopThr)``.
    warm_start:
        Scalings from a previous solve. Reusing them across outer GW iterations
        cuts the inner iteration count substantially, since the cost matrix
        changes only a little from one outer step to the next.

    Returns
    -------
    T:
        The transport plan.
    state:
        Scalings to feed back in as the next ``warm_start``.
    n_iter:
        Inner iterations performed.
    converged:
        ``False`` if the loop hit ``numItermax`` or bailed out on a numerical
        breakdown, in which case ``T`` is the last usable iterate.

    Notes
    -----
    **Numerical stabilization.** The kernel ``K = exp(-M/reg)`` underflows to
    zero whenever ``min(M)/reg`` exceeds ~745, which at the default
    ``reg = 5e-4`` happens for essentially every GW gradient. Subtracting a
    constant from ``M`` leaves the optimal plan unchanged (it rescales ``u`` and
    ``v`` by reciprocal factors), so we always shift by ``M.min()``. This is the
    main difference from the original implementation, which had no shift and
    reported "numerical errors" instead.

    Because the shift differs from call to call, a warm start computed under a
    previous shift must be rescaled by ``exp(-(c_new - c_old) / (2 reg))``,
    split evenly between ``u`` and ``v`` to halve the exponent. If that factor
    would itself overflow, we silently fall back to a cold start.
    """
    a = np.asarray(a, dtype=np.float64)
    b = np.asarray(b, dtype=np.float64)
    M = np.asarray(M, dtype=np.float64)

    # Shift the cost so the cheapest pair has cost 0; see the note above.
    shift = float(M.min())
    K = np.exp(-(M - shift) / reg)
    Kp = K / a[:, None]  # Precomputed for the u update.

    u, v = _init_scalings(a, b, warm_start, shift, reg)

    n_iter, err, converged = 0, np.inf, False
    while n_iter < numItermax:
        u_prev, v_prev = u, v

        KTu = K.T @ u
        v = b / KTu
        u = 1.0 / (Kp @ v)

        if not (np.all(np.isfinite(u)) and np.all(np.isfinite(v))):
            # Machine precision exhausted: keep the last good iterate.
            u, v = u_prev, v_prev
            break

        n_iter += 1
        if n_iter % check_every == 0:
            # Marginal violation on the target side; the source side is exact
            # by construction of the u update.
            marginal = (u[:, None] * K * v[None, :]).sum(axis=0)
            err = float(np.linalg.norm(marginal - b) ** 2)
            if err < stopThr:
                converged = True
                break

    T = u[:, None] * K * v[None, :]
    return T, SinkhornState(u, v, shift), n_iter, converged


def _init_scalings(
    a: np.ndarray,
    b: np.ndarray,
    warm_start: Optional[SinkhornState],
    shift: float,
    reg: float,
) -> Tuple[np.ndarray, np.ndarray]:
    """Produce the initial ``(u, v)``, rescaling a warm start if usable."""
    cold = (np.full(len(a), 1.0 / len(a)), np.full(len(b), 1.0 / len(b)))
    if warm_start is None:
        return cold

    # Correct for the change in cost shift; see the note in `sinkhorn`.
    exponent = -(shift - warm_start.shift) / (2.0 * reg)
    if abs(exponent) > 700.0:  # exp() would overflow/underflow float64
        return cold
    scale = np.exp(exponent)
    u, v = warm_start.u * scale, warm_start.v * scale
    if not (np.all(np.isfinite(u)) and np.all(np.isfinite(v))):
        return cold
    return u, v


