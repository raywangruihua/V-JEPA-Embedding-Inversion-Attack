def uniform_distribution(n: int) -> np.ndarray:
    """Uniform probability vector of length ``n``."""
    return np.full(n, 1.0 / n)


# Zipf-Mandelbrot shape parameters per language, from Piantadosi (2014).
_ZIPF_PARAMS: Dict[str, Tuple[float, float]] = {
    "en": (1.40, 1.88),
    "fi": (1.17, 0.60),
    "fr": (1.71, 2.09),
    "de": (1.10, 0.40),
    "es": (1.84, 3.81),
}
_ZIPF_DEFAULT = _ZIPF_PARAMS["en"]


def zipf_distribution(n: int, lang: str = "en") -> np.ndarray:
    """Zipf-Mandelbrot mass over a frequency-sorted vocabulary of size ``n``.

    ``p_i ~ 1 / (i + beta)^alpha``. Unlike the uniform marginal this encodes the
    prior that rank ``i`` in one language should carry comparable mass to rank
    ``i`` in the other. Unknown languages fall back to the English parameters.
    """
    alpha, beta = _ZIPF_PARAMS.get(lang, _ZIPF_DEFAULT)
    p = np.array([1.0 / ((i + 1) + beta) ** alpha for i in range(n)])
    return p / p.sum()


def _marginal(kind: str, n: int, lang: str) -> np.ndarray:
    """Build a marginal by name (``"uniform"`` or ``"zipf"``)."""
    if kind == "uniform":
        return uniform_distribution(n)
    if kind == "zipf":
        return zipf_distribution(n, lang)
    raise ValueError(f"unknown marginal distribution: {kind!r}")


