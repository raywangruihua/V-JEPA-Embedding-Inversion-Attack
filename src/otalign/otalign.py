class GromovWassersteinAligner:
    """Aligns two embedding spaces by solving an entropic Gromov-Wasserstein problem.

    The objective is

    .. math::
        \\min_T \\sum_{ijkl} L(C1_{ik}, C2_{jl}) T_{ij} T_{kl} - \\epsilon H(T)
        \\quad\\text{s.t.}\\quad T\\mathbf{1}=p,\\ T^\\top\\mathbf{1}=q,\\ T\\ge 0

    a *non-convex* quadratic program. It is solved by projected gradient: at each
    outer step the objective is linearized at the current ``T`` and the resulting
    entropic OT problem is solved by Sinkhorn. This converges to a stationary
    point, not a global optimum, so results depend on preprocessing and on
    ``entreg``.

    Parameters
    ----------
    anchor_vocab:
        Number of most-frequent words per language to include in the GW problem.
        Cost is quadratic in this number (see :meth:`fit`), so it is normally
        kept in the low thousands; the orthogonal map fitted afterwards is what
        extends coverage to the full vocabulary.
    metric:
        Distance used for the intra-domain matrices: ``"cosine"`` (default),
        ``"euclidean"`` or ``"sqeuclidean"``.
    normalize_vecs:
        Embedding preprocessing; see :func:`normalize_vectors`.
    normalize_dists:
        Rescaling applied to each distance matrix: ``"mean"`` (default),
        ``"max"``, ``"median"`` or ``"none"``.
    loss:
        ``"square_loss"`` (default) or ``"kl_loss"``.
    entreg:
        Entropic regularization ``epsilon``; the default of ``5e-4`` is the
        paper's. **This is the parameter most worth watching.** The independence
        coupling used to initialize the solve is itself very nearly a stationary
        point, and if ``entreg`` is too large for the problem the first Sinkhorn
        step returns something indistinguishable from it: the run "converges"
        immediately to a uniform coupling that encodes nothing. The symptom is a
        solve that stops after a couple of iterations with an entropy of about
        ``log(n*m) + 1``, followed by a warning about too few anchors. The safe
        direction is *smaller*. The usable ceiling falls as ``anchor_vocab``
        grows -- at 800 anchors, ``1e-3`` still works and ``5e-3`` does not.
    tol:
        Outer stopping threshold on ``||T - T_prev||_F``.
    maxiter:
        Maximum outer iterations.
    sinkhorn_maxiter, sinkhorn_tol:
        Inner Sinkhorn budget and tolerance.
    warm_start:
        Reuse Sinkhorn scalings across outer iterations. Usually a large speedup;
        disable it if you suspect it is hurting inner convergence.
    distribs:
        Marginals over each vocabulary: ``"uniform"`` (default) or ``"zipf"``.
    anchor_method:
        How to pick the pseudo-dictionary used to fit the orthogonal map:
        ``"mutual_nn"`` (default; pairs that are each other's best match --
        high precision, and the choice used in the paper) or ``"all"`` (every
        source word's top-1 target, higher recall but noisier).
    max_anchors:
        Cap on the number of anchor pairs, or ``None`` for all of them.
    verbose:
        Print a progress table.
    callback:
        Optional ``fn(GWIterate, T) -> None`` invoked every ``log_every``
        iterations. Useful for tracking downstream accuracy during the solve.
    """

    def __init__(
        self,
        anchor_vocab: int = 2000,
        metric: str = "cosine",
        normalize_vecs: str = "both",
        normalize_dists: str = "mean",
        loss: str = SQUARE_LOSS,
        entreg: float = 5e-4,
        tol: float = 1e-9,
        maxiter: int = 300,
        sinkhorn_maxiter: int = 1000,
        sinkhorn_tol: float = 1e-9,
        warm_start: bool = True,
        distribs: str = "uniform",
        anchor_method: str = "mutual_nn",
        max_anchors: Optional[int] = None,
        verbose: bool = True,
        log_every: int = 10,
        callback: Optional[Callable[[GWIterate, np.ndarray], None]] = None,
    ) -> None:
        self.anchor_vocab = anchor_vocab
        self.metric = metric
        self.normalize_vecs = normalize_vecs
        self.normalize_dists = normalize_dists
        self.loss = loss
        self.entreg = entreg
        self.tol = tol
        self.maxiter = maxiter
        self.sinkhorn_maxiter = sinkhorn_maxiter
        self.sinkhorn_tol = sinkhorn_tol
        self.warm_start = warm_start
        self.distribs = distribs
        self.anchor_method = anchor_method
        self.max_anchors = max_anchors
        self.verbose = verbose
        self.log_every = log_every
        self.callback = callback

        self.history: List[GWIterate] = []

    # -- main entry point ----------------------------------------------------

    def fit(
        self,
        src: WordVectors,
        trg: WordVectors,
        src_lang: str = "src",
        trg_lang: str = "trg",
    ) -> "Alignment":
        """Align two embedding spaces and return the resulting :class:`Alignment`.

        Both vocabularies are normalized in full first, then the first
        ``anchor_vocab`` rows of each are used for the GW problem. Normalizing
        before slicing keeps every vector -- including those GW never sees -- in
        the same frame, which is what makes the fitted orthogonal map valid over
        the whole vocabulary.

        ``src_lang`` / ``trg_lang`` are ISO codes used only to select
        Zipf parameters (when ``distribs="zipf"``) and to label output files.

        Cost
        ----
        With ``n = m = anchor_vocab``, memory is ``O(n^2)`` for each distance
        matrix -- at ``n = 20000`` that pair alone is ~6.4 GB in float64 -- and
        each outer iteration costs ``O(n^3)`` for the gradient plus ``O(n^2)``
        per inner Sinkhorn step.
        """
        src_norm = WordVectors(src.words, normalize_vectors(src.vectors, self.normalize_vecs))
        trg_norm = WordVectors(trg.words, normalize_vectors(trg.vectors, self.normalize_vecs))

        src_anchor = src_norm.head(self.anchor_vocab)
        trg_anchor = trg_norm.head(self.anchor_vocab)
        n, m = len(src_anchor), len(trg_anchor)

        if self.verbose:
            print(f"Solving GW over {n} x {m} words (dim {src_norm.dim}).")

        p = _marginal(self.distribs, n, src_lang)
        q = _marginal(self.distribs, m, trg_lang)

        coupling = self.solve(src_anchor.vectors, trg_anchor.vectors, p, q)

        alignment = Alignment(
            coupling=coupling,
            mapping=np.eye(src_norm.dim),
            src=src_norm,
            trg=trg_norm,
            src_lang=src_lang,
            trg_lang=trg_lang,
            history=list(self.history),
            metric=self.metric,
        )
        alignment.mapping = alignment.fit_mapping(
            anchor_method=self.anchor_method,
            max_anchors=self.max_anchors,
            verbose=self.verbose,
        )
        return alignment

    def solve(
        self,
        xs: np.ndarray,
        xt: np.ndarray,
        p: Optional[np.ndarray] = None,
        q: Optional[np.ndarray] = None,
    ) -> np.ndarray:
        """Run the GW iteration on raw matrices and return the coupling.

        Lower-level than :meth:`fit`: takes vectors that are *already*
        normalized, applies no post-processing, and returns just ``T``. Useful
        for aligning point clouds that are not word embeddings.
        """
        n, m = xs.shape[0], xt.shape[0]
        p = uniform_distribution(n) if p is None else np.asarray(p, dtype=np.float64)
        q = uniform_distribution(m) if q is None else np.asarray(q, dtype=np.float64)

        if self.verbose:
            print("Computing intra-domain distance matrices...")
        C1 = _pairwise_distances(xs, self.metric, self.normalize_dists)
        C2 = _pairwise_distances(xt, self.metric, self.normalize_dists)

        constC, hC1, hC2 = _loss_factorization(C1, C2, p, q, self.loss)

        T = np.outer(p, q)  # Independence coupling: the least committed start.
        state: Optional[SinkhornState] = None
        self.history = []
        started = time.time()

        if self.verbose:
            self._print_header()

        for it in range(self.maxiter + 1):
            T_prev = T
            gradient = _gw_gradient(constC, hC1, hC2, T)
            T, state, inner_iters, _ = sinkhorn(
                p,
                q,
                gradient,
                self.entreg,
                warm_start=state if self.warm_start else None,
                numItermax=self.sinkhorn_maxiter,
                stopThr=self.sinkhorn_tol,
            )

            delta = float(np.linalg.norm(T - T_prev))
            should_log = (it % self.log_every == 0) or delta <= self.tol

            if should_log or self.callback is not None:
                record = GWIterate(
                    iteration=it,
                    gw_distance=_gw_loss(constC, hC1, hC2, T),
                    entropy=_coupling_entropy(T),
                    delta=delta,
                    sinkhorn_iters=inner_iters,
                    elapsed=time.time() - started,
                )
                self.history.append(record)
                if self.verbose and should_log:
                    self._print_row(record)
                if self.callback is not None:
                    self.callback(record, T)

            if delta <= self.tol:
                if self.verbose:
                    print(f"Converged at iteration {it} (delta={delta:.2e}).")
                break
        else:
            if self.verbose:
                print(f"Stopped at maxiter={self.maxiter} (delta={delta:.2e}).")

        return T

    # -- progress reporting --------------------------------------------------

    @staticmethod
    def _print_header() -> None:
        head = "{:>6} {:>12} {:>12} {:>12} {:>8} {:>9}".format(
            "iter", "gw_dist", "entropy", "delta", "sink_it", "time(s)"
        )
        print("-" * len(head))
        print(head)
        print("-" * len(head))

    @staticmethod
    def _print_row(r: GWIterate) -> None:
        print(
            "{:6d} {:12.4e} {:12.4e} {:12.4e} {:8d} {:9.2f}".format(
                r.iteration, r.gw_distance, r.entropy, r.delta,
                r.sinkhorn_iters, r.elapsed,
            )
        )


def _coupling_entropy(T: np.ndarray) -> float:
    """Entropy ``-sum T (log T - 1)`` of a coupling, ignoring zero entries.

    This is the term the entropic regularizer maximizes. It rises as the plan
    blurs and falls as it sharpens toward a permutation, which makes it a useful
    read on whether ``entreg`` is set sensibly.
    """
    with np.errstate(divide="ignore", invalid="ignore"):
        terms = T * (np.log(T) - 1.0)
    return float(-np.nan_to_num(terms).sum())


