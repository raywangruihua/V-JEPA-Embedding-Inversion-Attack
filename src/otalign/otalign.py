def _loss_factorization(
    C1: np.ndarray,
    C2: np.ndarray,
    p: np.ndarray,
    q: np.ndarray,
    loss: str,
) -> Tuple[np.ndarray, np.ndarray, np.ndarray]:
    r"""Precompute the terms that make the GW gradient cheap.

    Evaluated naively, the GW objective is a sum over four indices and costs
    ``O(n^2 m^2)``. Peyre et al. (ICML 2016), Proposition 1, observe that for
    losses decomposable as ``L(x, y) = f1(x) + f2(y) - h1(x) h2(y)`` the tensor
    contraction reduces to

    .. math:: \mathcal{L}(C_1, C_2) \otimes T = \mathrm{constC} - h_1(C_1)\, T\, h_2(C_2)^\top

    which is a pair of matrix products, ``O(n^2 m + n m^2)``.

    - ``square_loss``: ``f1(x)=x^2/2``, ``f2(y)=y^2/2``, ``h1(x)=x``, ``h2(y)=y``
    - ``kl_loss``:     ``f1(x)=x log x - x``, ``f2(y)=y``, ``h1(x)=x``,
      ``h2(y)=log y`` (requires non-negative cost matrices)

    Returns ``(constC, hC1, hC2)``, all independent of ``T``.
    """
    if loss == SQUARE_LOSS:
        f1, f2 = lambda x: (x ** 2) / 2.0, lambda y: (y ** 2) / 2.0
        h1, h2 = lambda x: x, lambda y: y
    elif loss == KL_LOSS:
        f1, f2 = lambda x: x * np.log(x + 1e-15) - x, lambda y: y
        h1, h2 = lambda x: x, lambda y: np.log(y + 1e-15)
    else:
        raise ValueError(f"unknown loss function: {loss!r}")

    # constC_ij = sum_k f1(C1_ik) p_k + sum_l f2(C2_jl) q_l  -- rank-1 in each term.
    constC = (f1(C1) @ p)[:, None] + (f2(C2) @ q)[None, :]
    return constC, h1(C1), h2(C2)


def _gw_tensor(constC: np.ndarray, hC1: np.ndarray, hC2: np.ndarray, T: np.ndarray) -> np.ndarray:
    """The factorized tensor-matrix product ``L(C1, C2) (x) T``."""
    return constC - hC1 @ T @ hC2.T


def _gw_loss(constC: np.ndarray, hC1: np.ndarray, hC2: np.ndarray, T: np.ndarray) -> float:
    """GW objective value at ``T`` (excluding the entropic term)."""
    return float(np.sum(_gw_tensor(constC, hC1, hC2, T) * T))


def _gw_gradient(constC: np.ndarray, hC1: np.ndarray, hC2: np.ndarray, T: np.ndarray) -> np.ndarray:
    """Gradient of the GW objective at ``T``. Acts as a linear OT cost matrix."""
    return 2.0 * _gw_tensor(constC, hC1, hC2, T)


def _pairwise_distances(X: np.ndarray, metric: str, normalize: str) -> np.ndarray:
    """Intra-domain distance matrix, rescaled so the two languages are comparable.

    The rescaling is essential: GW compares distances across spaces, and the raw
    scales of two independently trained embedding spaces are arbitrary.
    """
    C = _cosine_distances(X) if metric == "cosine" else cdist(X, X, metric=metric)
    if normalize in (None, "none"):
        return C
    if normalize == "mean":
        return C / C.mean()
    if normalize == "max":
        return C / C.max()
    if normalize == "median":
        return C / np.median(C)
    raise ValueError(f"unknown distance normalization: {normalize!r}")


def _cosine_distances(X: np.ndarray) -> np.ndarray:
    """Self-distance matrix under the cosine metric, computed as one GEMM.

    ``cdist(X, X, metric="cosine")`` evaluates the dot product of every pair in
    a scalar, single-threaded C loop. Since cosine distance is
    ``1 - <x, y> / (||x|| ||y||)``, unit-normalizing the rows first reduces the
    whole matrix to ``1 - Xn @ Xn.T`` -- a single BLAS call, which is both
    blocked for cache and multi-threaded. Same values, orders of magnitude
    faster; the O(n*d) normalization is negligible beside the O(n^2 d) product.

    One deliberate difference from ``cdist``: a zero row has no direction, and
    ``cdist`` reports its distances as ``nan``. Here :func:`_unit_rows` leaves
    it at zero, so it sits at distance 1 from everything. That keeps a single
    degenerate vector from poisoning the entire GW objective with ``nan``.
    """
    Xn = _unit_rows(np.asarray(X, dtype=np.float64))
    C = 1.0 - Xn @ Xn.T
    # Rounding can put entries a few ulp outside the true range of the metric,
    # and leaves ~1e-16 rather than 0 on the diagonal. Both matter: `kl_loss`
    # takes the log of these, and the diagonal is what fixes the loss's scale.
    np.clip(C, 0.0, 2.0, out=C)
    np.fill_diagonal(C, 0.0)
    return C


