@dataclass
class WordVectors:
    """A vocabulary paired with its embedding matrix.

    Attributes
    ----------
    words:
        Vocabulary, in file order. Embedding files are conventionally sorted by
        descending corpus frequency, and the rest of this module relies on that:
        "the first ``k`` words" is taken to mean "the ``k`` most frequent words".
    vectors:
        Array of shape ``(len(words), dim)``. Row ``i`` is the vector of
        ``words[i]``.
    """

    words: List[str]
    vectors: np.ndarray

    def __post_init__(self) -> None:
        if len(self.words) != self.vectors.shape[0]:
            raise ValueError(
                f"vocabulary size ({len(self.words)}) does not match number of "
                f"vectors ({self.vectors.shape[0]})"
            )
        # First occurrence wins, matching the behaviour of the original loader.
        self._word2ind: Dict[str, int] = {}
        for i, w in enumerate(self.words):
            self._word2ind.setdefault(w, i)

    # -- basic container protocol -------------------------------------------

    def __len__(self) -> int:
        return len(self.words)

    def __repr__(self) -> str:
        return f"WordVectors(n={len(self)}, dim={self.dim})"

    @property
    def dim(self) -> int:
        """Embedding dimensionality."""
        return int(self.vectors.shape[1])

    @property
    def word2ind(self) -> Dict[str, int]:
        """Mapping from word to row index."""
        return self._word2ind

    def index(self, word: str) -> Optional[int]:
        """Row index of ``word``, or ``None`` if it is out of vocabulary."""
        return self._word2ind.get(word)

    def head(self, n: Optional[int]) -> "WordVectors":
        """The ``n`` most frequent words, as a new :class:`WordVectors`.

        Returns ``self`` unchanged when ``n`` is ``None`` or exceeds the
        vocabulary size. The returned object *views* the same underlying array,
        so it is cheap but is invalidated by in-place edits.
        """
        if n is None or n >= len(self):
            return self
        return WordVectors(self.words[:n], self.vectors[:n])

    # -- persistence ---------------------------------------------------------

    @classmethod
    def load(
        cls,
        path: str,
        max_vocab: Optional[int] = None,
        encoding: str = "utf-8",
        dtype: str = "float64",
    ) -> "WordVectors":
        """Read a whitespace-delimited embedding file.

        Accepts both the word2vec/fastText convention (a ``"<count> <dim>"``
        header line) and plain headerless files.

        Parameters
        ----------
        path:
            File to read.
        max_vocab:
            Read at most this many vectors. Since files are frequency-sorted
            this keeps the most frequent words. ``None`` reads everything.
        dtype:
            Storage dtype. ``float64`` matches the original implementation;
            ``float32`` halves memory at no practical cost in accuracy.
        """
        with open(path, encoding=encoding, errors="surrogateescape") as handle:
            first = handle.readline()
            header = _parse_header(first)

            if header is not None:
                count, dim = header
                n = count if max_vocab is None else min(max_vocab, count)
                words: List[str] = []
                matrix = np.empty((n, dim), dtype=dtype)
                for i in range(n):
                    line = handle.readline()
                    if not line:  # File is shorter than its header claims.
                        matrix = matrix[: len(words)]
                        break
                    word, vec = line.rstrip("\n").split(" ", 1)
                    words.append(word)
                    matrix[i] = np.fromstring(vec, sep=" ", dtype=dtype)
                return cls(words, matrix)

            # Headerless: the first line is already a vector.
            words, rows = [], []
            for line in _prepend(first, handle):
                if max_vocab is not None and len(words) >= max_vocab:
                    break
                stripped = line.rstrip("\n")
                if not stripped:
                    continue
                word, vec = stripped.split(" ", 1)
                words.append(word)
                rows.append(np.fromstring(vec, sep=" ", dtype=dtype))
            return cls(words, np.vstack(rows))

    def save(self, path: str, encoding: str = "utf-8") -> None:
        """Write the vectors back out in word2vec text format."""
        with open(path, "w", encoding=encoding, errors="surrogateescape") as handle:
            handle.write("%d %d\n" % self.vectors.shape)
            for word, vec in zip(self.words, self.vectors):
                handle.write(word + " " + " ".join("%.6g" % x for x in vec) + "\n")


def _parse_header(line: str) -> Optional[Tuple[int, int]]:
    """Return ``(count, dim)`` if ``line`` is a word2vec header, else ``None``."""
    parts = line.split()
    if len(parts) != 2:
        return None
    try:
        return int(parts[0]), int(parts[1])
    except ValueError:
        return None


def _prepend(first: str, rest: Iterable[str]) -> Iterable[str]:
    """Iterate ``first`` followed by ``rest`` (used to un-consume a read line)."""
    yield first
    for item in rest:
        yield item


def normalize_vectors(X: np.ndarray, method: str = "both") -> np.ndarray:
    """Preprocess an embedding matrix. Returns a new array; ``X`` is untouched.

    Preprocessing matters a great deal for GW, because the objective sees only
    the *intra*-domain distance matrices: any transformation that changes the
    shape of a space changes the problem.

    Parameters
    ----------
    method:
        - ``"mean"``      -- subtract the column mean (centering).
        - ``"both"``      -- centering, then scale each row to unit norm.
                             This is the default used in the paper.
        - ``"unit"``      -- unit-norm rows only, no centering.
        - ``"whiten"``    -- centering, then PCA whitening (identity covariance).
        - ``"whiten_zca"``-- centering, then ZCA whitening (identity covariance,
                             but staying as close to the original axes as
                             possible).
        - ``"none"``      -- return a copy unchanged.

    Notes
    -----
    Whitening is applied *once, over the whole vocabulary passed in*. Callers
    should therefore normalize the full embedding matrix before slicing out a
    subset, so that every vector ends up in the same frame -- see
    :meth:`GromovWassersteinAligner.fit`, which does exactly that.
    """
    X = np.asarray(X, dtype=np.float64)

    if method in (None, "none"):
        return X.copy()
    if method == "unit":
        return _unit_rows(X)
    if method == "mean":
        return X - X.mean(axis=0)
    if method == "both":
        return _unit_rows(X - X.mean(axis=0))
    if method in ("whiten", "whiten_zca"):
        centered = X - X.mean(axis=0)
        return _whiten(centered, zca=(method == "whiten_zca"))
    raise ValueError(f"unknown normalization method: {method!r}")


def _unit_rows(X: np.ndarray) -> np.ndarray:
    """Scale each row to unit L2 norm, leaving zero rows alone."""
    norms = np.linalg.norm(X, axis=1)
    norms[norms == 0] = 1.0
    return X / norms[:, None]


def _whiten(X: np.ndarray, zca: bool = False, eps: float = 1e-8) -> np.ndarray:
    """Whiten centered data so that the covariance becomes the identity.

    PCA whitening applies ``W = L^(-1/2) U'`` where ``Cov = U L U'``. ZCA
    additionally rotates back, ``W = U L^(-1/2) U'``, which keeps the whitened
    vectors as close as possible to the originals.

    ``eps`` regularizes the eigenvalues; without it, near-null directions -- of
    which word embeddings have plenty -- blow up.
    """
    cov = np.cov(X, rowvar=False)
    eigvals, eigvecs = np.linalg.eigh(cov)
    inv_sqrt = 1.0 / np.sqrt(np.maximum(eigvals, 0.0) + eps)
    # Rows of `W` are the whitening directions, so we right-multiply by W.T.
    W = (eigvecs * inv_sqrt) @ eigvecs.T if zca else (eigvecs * inv_sqrt).T
    return X @ W.T


