"""
otalign
=======

Generated by Claude.

Self-contained implementation of **Gromov-Wasserstein alignment of word embedding
spaces** (Alvarez-Melis & Jaakkola, EMNLP 2018) for unsupervised bilingual lexicon
induction (BLI).

The problem
-----------
Given monolingual word embeddings for two languages and *no* seed dictionary,
recover word-to-word translations. Vectors from the two spaces are not directly
comparable -- there is no meaningful ``d(x_i, y_j)`` -- so ordinary optimal
transport does not apply. Gromov-Wasserstein (GW) instead compares each space's
*internal* geometry: it only needs the intra-domain distance matrices ``C1`` and
``C2``, and looks for a soft matching that makes the two relational structures
agree. Informally: *"dog" is to "cat" as "perro" is to "gato"*.

The pipeline
------------
1. Normalize both embedding matrices (:func:`normalize_vectors`).
2. Take the ``anchor_vocab`` most frequent words of each language and solve the
   entropic GW problem over them (:class:`GromovWassersteinAligner`), yielding a
   soft coupling ``T``.
3. Read mutual nearest neighbours out of ``T`` -- an automatically induced seed
   dictionary -- and fit an orthogonal map ``P`` by Procrustes
   (:func:`orthogonal_procrustes`).
4. Because ``P`` is ``d x d`` it applies to the *whole* vocabulary, so
   translations are available well beyond the words GW actually saw
   (:class:`Alignment`).

Nothing here is trained by gradient descent: there are no learned parameters.
The "model" is a coupling matrix obtained by constrained optimization plus an
orthogonal matrix obtained in closed form from an SVD. The input embeddings are
frozen throughout.

Quick start
-----------
::

    import otalign

    src = otalign.WordVectors.load("wiki.en.vec", max_vocab=200_000)
    trg = otalign.WordVectors.load("wiki.es.vec", max_vocab=200_000)

    alignment = otalign.align(src, trg, anchor_vocab=2000, maxiter=300)

    alignment.translate(["dog", "house"], k=5)
    # {'dog': ['perro', ...], 'house': ['casa', ...]}

    gold, _ = otalign.load_dictionary("en-es.0-5000.txt", src, trg)
    alignment.precision_at_k(gold)
    # {1: 0.63, 5: 0.79, 10: 0.83}

There is also a command line entry point; see ``python otalign.py --help``.

Dependencies
------------
``numpy`` and ``scipy`` only. The original code depended on POT (and, for the
GPU path, on ``cudamat``); the handful of primitives actually needed -- Sinkhorn,
the GW loss factorization, barycentric mapping -- are implemented directly here,
which removes the dependency churn that broke the original GPU path.

License: GPL v3.0 (inherited from the original implementation). Embedding text
I/O follows the format used by Artetxe's VecMap and Facebook's MUSE.
"""

