def orthogonal_procrustes(X: np.ndarray, Y: np.ndarray) -> np.ndarray:
    r"""Solve :math:`\min_P \|X - Y P^\top\|_F` subject to :math:`P^\top P = I`.

    Closed form: with :math:`X^\top Y = U \Sigma V^\top`, the optimum is
    :math:`P = U V^\top`.

    Rows are observations (the ML convention), not columns. With ``X`` a block
    of source vectors and ``Y`` the corresponding target vectors, the returned
    ``P`` maps *target into source* space as ``Y @ P.T``.
    """
    U, _, Vt = np.linalg.svd(X.T @ Y)
    return U @ Vt


def mutual_nearest_neighbors(scores: np.ndarray) -> List[Tuple[int, int]]:
    """Index pairs ``(i, j)`` that are each other's highest-scoring match.

    Mutual agreement is a strong precision filter: it discards source words whose
    best target already prefers someone else, which is exactly the failure mode
    of hub words. The survivors serve as a seed dictionary that was never
    supervised.
    """
    best_for_src = scores.argmax(axis=1)
    best_for_trg = scores.argmax(axis=0)
    return [(i, int(j)) for i, j in enumerate(best_for_src) if best_for_trg[j] == i]


def _mean_topk(scores: np.ndarray, knn: int, axis: int) -> np.ndarray:
    """Mean of the ``knn`` largest values along ``axis``.

    ``axis=1`` gives, for each row, its mean similarity to its ``knn`` best
    columns; ``axis=0`` does the same per column.
    """
    S = scores if axis == 1 else scores.T
    knn = min(knn, S.shape[1])
    idx = np.argpartition(S, -knn, axis=1)[:, -knn:]
    return np.take_along_axis(S, idx, axis=1).mean(axis=1)


def csls(scores: np.ndarray, knn: int = 10) -> np.ndarray:
    """Cross-domain Similarity Local Scaling (Conneau et al., 2018).

    ``csls(x, y) = 2 s(x, y) - r_s(x) - r_t(y)``, where each ``r`` is the mean
    similarity to the ``knn`` nearest neighbours in the other space.

    This corrects for *hubness*: in high dimensions a few vectors sit close to
    very many others and win nearest-neighbour queries they have no business
    winning. Penalizing each point by its own neighbourhood density removes the
    advantage. Costs ``O(nm)`` memory, since it needs the whole score matrix.
    """
    r_s = _mean_topk(scores, knn, axis=1)
    r_t = _mean_topk(scores, knn, axis=0)
    return 2.0 * scores - r_s[:, None] - r_t[None, :]


@dataclass
class Alignment:
    """The fitted alignment between two embedding spaces.

    Attributes
    ----------
    coupling:
        Soft matching ``T`` of shape ``(n_anchor_src, n_anchor_trg)``, defined
        only over the words GW actually optimized over.
    mapping:
        Orthogonal ``P`` of shape ``(dim, dim)``. Maps target into source space
        as ``xt @ P.T``, and therefore applies to the *entire* vocabulary.
    src, trg:
        The full, normalized vocabularies.
    history:
        Per-iteration solver diagnostics.
    """

    coupling: np.ndarray
    mapping: np.ndarray
    src: WordVectors
    trg: WordVectors
    src_lang: str = "src"
    trg_lang: str = "trg"
    history: List[GWIterate] = field(default_factory=list)

    #: Default retrieval scoring; see :meth:`score_matrix`.
    score_type: str = "projected"
    #: Default neighbourhood correction: ``"csls"`` or ``None``.
    adjust: Optional[str] = "csls"
    #: Metric for distance-based scoring. Cosine by default, matching the
    #: default used for the GW distance matrices.
    metric: str = "cosine"

    @property
    def n_anchor_src(self) -> int:
        """Number of source words covered by :attr:`coupling`."""
        return int(self.coupling.shape[0])

    @property
    def n_anchor_trg(self) -> int:
        """Number of target words covered by :attr:`coupling`."""
        return int(self.coupling.shape[1])

    # -- fitting the linear map ---------------------------------------------

    def fit_mapping(
        self,
        anchor_method: str = "mutual_nn",
        max_anchors: Optional[int] = None,
        verbose: bool = False,
    ) -> np.ndarray:
        """Fit the orthogonal map from anchor pairs read out of the coupling.

        This is the step that turns a coupling over a few thousand words into
        something usable over the whole vocabulary. See
        :func:`mutual_nearest_neighbors` and :func:`orthogonal_procrustes`.
        """
        scores = self.coupling
        if anchor_method == "mutual_nn":
            pairs = mutual_nearest_neighbors(scores)
        elif anchor_method == "all":
            pairs = [(i, int(j)) for i, j in enumerate(scores.argmax(axis=1))]
        else:
            raise ValueError(f"unknown anchor method: {anchor_method!r}")

        dim = self.src.dim
        if len(pairs) < dim:
            # Fewer anchors than dimensions leaves the Procrustes fit
            # underdetermined: the SVD still returns an orthogonal matrix, but
            # it is arbitrary on the unconstrained subspace, so the map would be
            # silently meaningless.
            message = (
                f"only {len(pairs)} anchor pairs for a {dim}-dimensional map. "
                "The coupling is close to degenerate -- most often because "
                "`entreg` is too large for this `anchor_vocab`, leaving the "
                "solver at the independence coupling it started from. Try "
                "lowering `entreg` (5e-4 is the paper's default), raising "
                "`maxiter`, or a different `normalize_vecs`."
            )
            if not pairs:
                raise RuntimeError(message)
            warnings.warn(message, RuntimeWarning, stacklevel=2)

        if max_anchors:
            pairs = pairs[:max_anchors]
        if verbose:
            print(f"Fitting orthogonal map from {len(pairs)} anchors ({anchor_method}).")

        idx_src = [i for i, _ in pairs]
        idx_trg = [j for _, j in pairs]
        return orthogonal_procrustes(self.src.vectors[idx_src], self.trg.vectors[idx_trg])

    # -- scoring -------------------------------------------------------------

    def score_matrix(
        self,
        score_type: Optional[str] = None,
        adjust: Optional[str] = "__default__",
        n_src: Optional[int] = None,
        n_trg: Optional[int] = None,
        csls_knn: int = 10,
    ) -> np.ndarray:
        """Translation scores (higher is better) for a slice of the vocabularies.

        Parameters
        ----------
        score_type:
            - ``"coupling"``    -- the GW coupling itself. Restricted to the
              anchor words; the sharpest signal where it is defined.
            - ``"projected"``   -- negative distance after applying ``P``.
              Defined over the whole vocabulary. The default.
            - ``"barycentric"`` -- map each target word to the coupling-weighted
              average of its source matches, then measure distance there.
              Restricted to the anchor words.
        adjust:
            ``"csls"`` or ``None``. Defaults to :attr:`adjust`.
        n_src, n_trg:
            Restrict to the first N words of each vocabulary. Required in
            practice for ``"projected"`` -- the full matrix is ``|V_s| x |V_t|``,
            which for two 200k vocabularies is 320 GB.

        Notes
        -----
        Memory is ``O(n_src * n_trg)``, and CSLS needs the matrix materialized,
        so cap both when working beyond the anchor set.
        """
        score_type = score_type or self.score_type
        adjust = self.adjust if adjust == "__default__" else adjust

        if score_type == "coupling":
            scores = self._slice_anchor(self.coupling, score_type, n_src, n_trg)
        elif score_type == "barycentric":
            scores = self._slice_anchor(self._barycentric_scores(), score_type, n_src, n_trg)
        elif score_type == "projected":
            xs = self.src.vectors[: n_src or len(self.src)]
            xt = self.trg.vectors[: n_trg or len(self.trg)]
            scores = -cdist(xs, xt @ self.mapping.T, metric=self.metric)
        else:
            raise ValueError(f"unknown score type: {score_type!r}")

        if adjust == "csls":
            scores = csls(scores, knn=csls_knn)
        elif adjust not in (None, "none"):
            raise ValueError(f"unknown score adjustment: {adjust!r}")
        return scores

    def _slice_anchor(
        self, scores: np.ndarray, score_type: str, n_src: Optional[int], n_trg: Optional[int]
    ) -> np.ndarray:
        """Clip an anchor-only score matrix, rejecting out-of-range requests."""
        if (n_src or 0) > scores.shape[0] or (n_trg or 0) > scores.shape[1]:
            raise ValueError(
                f"score_type={score_type!r} is only defined over the "
                f"{scores.shape[0]}x{scores.shape[1]} anchor vocabulary; use "
                f"score_type='projected' for the full vocabulary."
            )
        return scores[: n_src or scores.shape[0], : n_trg or scores.shape[1]]

    def _barycentric_scores(self) -> np.ndarray:
        """Score anchors by distance after barycentric projection of the target.

        Each target word is replaced by the coupling-weighted mean of the source
        words it is matched to, which places both languages in the source space
        without ever fitting a linear map.
        """
        weights = self.coupling.T / self.coupling.sum(axis=0)[:, None]
        trg_in_src = np.nan_to_num(weights) @ self.src.vectors[: self.n_anchor_src]
        return -cdist(self.src.vectors[: self.n_anchor_src], trg_in_src, metric=self.metric)

    # -- retrieval -----------------------------------------------------------

    def translate(
        self,
        words: Sequence[str],
        k: int = 1,
        score_type: Optional[str] = None,
        adjust: Optional[str] = "__default__",
        n_trg: Optional[int] = 50_000,
        csls_knn: int = 10,
    ) -> Dict[str, List[str]]:
        """Return the top-``k`` translation candidates for each of ``words``.

        Out-of-vocabulary queries are omitted from the result rather than raising.

        ``n_trg`` caps the candidate pool to the most frequent target words,
        which bounds both memory and the damage a rare-word hub can do. Pass
        ``None`` to search the entire target vocabulary.
        """
        score_type = score_type or self.score_type
        adjust = self.adjust if adjust == "__default__" else adjust

        indices, present = [], []
        for word in words:
            idx = self.src.index(word)
            if idx is not None:
                indices.append(idx)
                present.append(word)
        if not indices:
            return {}

        n_src = max(indices) + 1
        scores = self.score_matrix(
            score_type=score_type, adjust=adjust, n_src=n_src, n_trg=n_trg, csls_knn=csls_knn
        )
        return {
            word: [self.trg.words[j] for j in _topk(scores[idx], k)]
            for word, idx in zip(present, indices)
        }

    def precision_at_k(
        self,
        gold: Dict[int, Set[int]],
        ks: Sequence[int] = (1, 5, 10),
        score_type: Optional[str] = None,
        adjust: Optional[str] = "__default__",
        n_trg: Optional[int] = 50_000,
        csls_knn: int = 10,
        verbose: bool = False,
    ) -> Dict[int, float]:
        """Precision@k against a gold dictionary of *index* pairs.

        ``gold`` maps a source row index to the set of acceptable target row
        indices, as returned by :func:`load_dictionary`.

        The denominator is the full size of ``gold``: source words that fall
        outside the scored slice count as errors rather than being dropped. That
        matches the original implementation and keeps numbers comparable to
        published results, but it means a small ``n_trg`` depresses the score
        rather than silently shrinking the test set.
        """
        score_type = score_type or self.score_type
        adjust = self.adjust if adjust == "__default__" else adjust
        if not gold:
            raise ValueError("gold dictionary is empty")

        n_src = max(gold) + 1
        scores = self.score_matrix(
            score_type=score_type, adjust=adjust, n_src=n_src, n_trg=n_trg, csls_knn=csls_knn
        )
        n_scored_src, n_scored_trg = scores.shape

        correct = {k: 0 for k in ks}
        evaluable = 0
        for src_idx, trg_idxs in gold.items():
            in_range = [j for j in trg_idxs if j < n_scored_trg]
            if src_idx >= n_scored_src or not in_range:
                continue  # Counts against the denominator; see the docstring.
            evaluable += 1
            ranking = _topk(scores[src_idx], max(ks))
            for k in ks:
                if set(ranking[:k]) & set(in_range):
                    correct[k] += 1

        precisions = {k: correct[k] / len(gold) for k in ks}
        if verbose:
            coverage = evaluable / len(gold)
            print(
                "coverage: {:6.2%}   ".format(coverage)
                + "   ".join("P@{}: {:6.2%}".format(k, v) for k, v in precisions.items())
            )
        return precisions

    # -- exporting -----------------------------------------------------------

    def project_target(self) -> WordVectors:
        """The full target vocabulary mapped into the source space (``xt @ P.T``)."""
        return WordVectors(self.trg.words, self.trg.vectors @ self.mapping.T)

    def export(self, outdir: str) -> None:
        """Write both vocabularies into a shared space, plus the fitted arrays.

        Produces ``vectors-<src_lang>.txt`` (unchanged source),
        ``vectors-<trg_lang>.txt`` (target projected into the source space) and
        ``alignment.npz``.
        """
        os.makedirs(outdir, exist_ok=True)
        self.src.save(os.path.join(outdir, f"vectors-{self.src_lang}.txt"))
        self.project_target().save(os.path.join(outdir, f"vectors-{self.trg_lang}.txt"))
        self.save(os.path.join(outdir, "alignment.npz"))

    def save(self, path: str) -> None:
        """Persist the coupling, the mapping and both vocabularies to an ``.npz``."""
        np.savez_compressed(
            path,
            coupling=self.coupling,
            mapping=self.mapping,
            src_vectors=self.src.vectors,
            trg_vectors=self.trg.vectors,
            src_words=np.array(self.src.words, dtype=object),
            trg_words=np.array(self.trg.words, dtype=object),
            langs=np.array([self.src_lang, self.trg_lang], dtype=object),
        )

    @classmethod
    def load(cls, path: str) -> "Alignment":
        """Reload an alignment written by :meth:`save`."""
        data = np.load(path, allow_pickle=True)
        langs = data["langs"]
        return cls(
            coupling=data["coupling"],
            mapping=data["mapping"],
            src=WordVectors(list(data["src_words"]), data["src_vectors"]),
            trg=WordVectors(list(data["trg_words"]), data["trg_vectors"]),
            src_lang=str(langs[0]),
            trg_lang=str(langs[1]),
        )


def _topk(row: np.ndarray, k: int) -> List[int]:
    """Indices of the ``k`` largest entries of ``row``, best first.

    Uses ``argpartition`` to avoid sorting the whole row, then sorts only the
    ``k`` survivors.
    """
    k = min(k, row.shape[0])
    part = np.argpartition(row, -k)[-k:]
    return part[np.argsort(-row[part])].tolist()


